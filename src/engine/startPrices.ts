/**
 * Known starting price for a ticker on a start date, or undefined to fall back to a
 * simulated one. Funds interpolate (in log terms) between the nearest anchors that list them
 * and hold the end values outside that range; stocks need an anchor on exactly that date.
 */
export function knownStartPrice(date: IsoDate, ticker: string): number | undefined {
  const exact = ANCHORS.find((a) => a.date === date)?.prices[ticker];
  if (exact !== undefined || !FUNDS.has(ticker)) return exact;
  const listed = ANCHORS.filter((a) => a.prices[ticker] !== undefined);
  if (listed.length === 0) return undefined;
  const t = toDayNumber(date);
  const after = listed.findIndex((a) => toDayNumber(a.date) > t);
  const price = (a: PriceAnchor | undefined) => a?.prices[ticker] ?? 0;
  if (after === 0) return price(listed[0]);
  if (after === -1) return price(listed[listed.length - 1]);
  const a = listed[after - 1];
  const b = listed[after];
  if (!a || !b) return undefined;
  const t0 = toDayNumber(a.date);
  const w = (t - t0) / (toDayNumber(b.date) - t0);
  const p = Math.exp((1 - w) * Math.log(price(a)) + w * Math.log(price(b)));
  return Math.round(p * 100) / 100;
}
